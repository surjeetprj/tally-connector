"""Only capabilities required by the local read/link milestone."""
from typing import Protocol

from innoforia_tally_connector.domain.masters import (
    Binding, ConfirmedPartyLink, PartyObservation, PartyScan, Side,
)
from innoforia_tally_connector.domain.experiments import ActivityPage, ExperimentPreview, ExperimentResult, Preflight, TargetIdentity
from innoforia_tally_connector.domain.party_transfer import PartyDraft
from innoforia_tally_connector.domain.batches import TransferPolicy, TransferBatch, BatchPage
from innoforia_tally_connector.domain.commands import Command


class PartyReader(Protocol):
    # Implementations must verify authenticated business / company identity and
    # classification, not simply stamp the requested binding on returned data.
    def scan(self, binding: Binding) -> PartyScan: ...
    def detail(self, binding: Binding, identity: str) -> PartyObservation: ...


class PartyLinks(Protocol):
    def save(self, link: ConfirmedPartyLink) -> None: ...
    def find(self, binding: Binding, side: Side, identity: str) -> ConfirmedPartyLink | None: ...
    def list(self, binding: Binding, offset: int = 0, limit: int = 200) -> tuple[ConfirmedPartyLink, ...]: ...


class PartyDestination(Protocol):
    def validate(self, draft: PartyDraft) -> dict[str, str]: ...
    def collisions(self, binding: Binding, name: str) -> tuple[str, ...]: ...
    def collision_names(self, binding: Binding, scan: PartyScan | None = None) -> tuple[str, ...]: ...
    def preflight(self, binding: Binding, draft: PartyDraft) -> Preflight: ...
    def create(self, preview: ExperimentPreview, preflight: Preflight) -> TargetIdentity: ...
    def read_back(self, preview: ExperimentPreview, target: TargetIdentity) -> tuple[PartyObservation, TargetIdentity, bool]: ...


class PartyTransferStore(Protocol):
    def save_preview(self, preview: ExperimentPreview, replaces=None) -> ExperimentResult: ...
    def get(self, identity: str | None, binding: Binding) -> ExperimentResult | None: ...
    def begin_attempt(self, preview: ExperimentPreview, command, preflight: Preflight) -> None: ...
    def result(self, identity, operation_id, state, **evidence) -> None: ...
    def complete_transfer(self, record, command, source, destination, comparisons, target) -> ExperimentResult: ...
    def cancel(self, identity: str, binding: Binding) -> ExperimentResult: ...
    def history(self, binding: Binding, offset=0, status=None, kind=None) -> ActivityPage: ...
    def reconciliation_candidates(self, binding: Binding) -> tuple[ExperimentResult, ...]: ...


class PartyBatchStore(Protocol):
    def policy(self, binding: Binding) -> TransferPolicy | None: ...
    def save_policy(self, policy: TransferPolicy) -> TransferPolicy: ...
    def save_draft(self, batch: TransferBatch) -> TransferBatch: ...
    def get(self, identity: str, binding: Binding) -> TransferBatch: ...
    def history(self, binding: Binding, offset: int = 0) -> BatchPage: ...
    def approve(self, command: Command) -> TransferBatch: ...
    def activate(self, command: Command) -> bool: ...
    def finish_step(self, command: Command, pause: bool = False) -> None: ...
    def cancel(self, identity: str, binding: Binding) -> TransferBatch: ...
    def release_resolved(self, binding: Binding) -> None: ...
